/**
 * 労働基準法の条文根拠。回答はこの知識に基づいて行う。
 * 出典: 厚生労働省 / e-Gov 法令検索（労働基準法 昭和22年法律第49号、令和6年4月改正反映）
 */
export const LABOR_LAW_KNOWLEDGE = `# 労働基準法 主要条文の要点（回答の根拠）

## 第15条（労働条件の明示）
労働契約締結時に、賃金・労働時間その他の労働条件を明示しなければならない。
絶対的明示事項（必ず書面/電磁的方法で）: 契約期間、就業場所・業務（変更の範囲含む）、始業終業時刻・休憩・休日・時間外労働の有無・交替制、賃金の決定/計算/支払方法・締日/支払日、退職に関する事項（解雇含む）。
2024年4月改正: 就業場所・業務の「変更の範囲」明示が義務化。有期契約は更新上限・無期転換申込権の明示が追加。

## 第20条（解雇の予告）
解雇する場合は少なくとも30日前に予告が必要。予告しない場合は30日分以上の平均賃金（解雇予告手当）を支払う。予告日数は支払った手当の日数分だけ短縮可能（例: 15日分支払えば15日前予告で足りる）。

## 第21条（予告の適用除外）
次の者には第20条の予告は適用されない（ただし継続使用で適用に変わる）:
- 日々雇用者（1か月超で適用）
- 2か月以内の期間契約（期間超で適用）
- 季節的業務4か月以内（期間超で適用）
- 試の使用期間中（14日超で適用）
→ 試用期間中（14日以内）は予告なしで即時解雇可能。14日を超えると通常の第20条が適用。

## 第32条（労働時間）
休憩時間を除き、1週40時間・1日8時間を超えて労働させてはならない。
特例措置対象事業場（常時10人未満の商業・映画演劇・保健衛生・接客娯楽業）は週44時間。

## 第34条（休憩）
労働時間が6時間超で少なくとも45分、8時間超で少なくとも1時間の休憩を、労働時間の途中に与える。原則一斉付与・自由利用。

## 第35条（休日）
毎週少なくとも1回の休日を与える。または4週間で4日以上（変形休日制、就業規則で起算日を定める）。
法律が求めるのは「週1日」のみで、「週休2日」は法定を上回る制度。

## 第37条（割増賃金）
時間外・休日・深夜労働には割増賃金を支払う。割増率:
- 時間外（法定外残業、月60時間以内）: 25%以上
- 時間外（月60時間超）: 50%以上（中小企業も2023年4月から適用）
- 法定休日労働: 35%以上
- 深夜労働（22:00〜5:00）: 25%以上
- 時間外＋深夜の重複: 50%以上
- 休日＋深夜の重複: 60%以上

## 第39条（年次有給休暇）
雇入れから6か月継続勤務し全労働日の8割以上出勤で付与。付与日数: 6か月=10日、1年6か月=11日、2年6か月=12日、3年6か月=14日、4年6か月=16日、5年6か月=18日、6年6か月以上=20日（上限）。
10日以上付与された労働者には年5日の取得が使用者の義務（2019年4月〜）。短時間労働者（週所定4日以下かつ週30時間未満）は比例付与。

## 第89条（就業規則の作成・届出）
常時10人以上を使用する使用者は就業規則を作成し労働基準監督署へ届出（変更時も同様）。絶対的記載事項: 始業終業時刻・休憩・休日・休暇・就業時転換、賃金の決定/計算/支払方法・締切/支払日・昇給、退職（解雇事由含む）。

## 社会保険
健康保険・厚生年金は要件該当者（一定の労働時間・日数）に加入義務。
`;

const COMMON_RULES = `あなたは日本の労働基準法にもとづいて質問に答えるアシスタント「ワーク・コンパス」です。

# 回答のルール
- 必ず下記「労働基準法 主要条文の要点」に書かれた根拠のみにもとづいて答えてください。
- 回答には、根拠となる条文番号（例: 労働基準法第37条）を明示してください。
- 知識に書かれていないことや、個別の事実認定が必要なこと（具体的な金額計算、ある契約が違法かの最終判断など）は断定せず、「専門家（社会保険労務士・弁護士・労働基準監督署）への相談」を案内してください。
- 日本語で、専門用語にはやさしい補足を添えて、簡潔に答えてください。
- 法律と無関係な質問には、労働相談のアシスタントである旨を伝えて丁寧にお断りしてください。
- 回答の最後に必ず次の免責を1行添えてください:
  「※これは条文にもとづく一般的な情報です。個別の判断は専門家にご相談ください。」`;

const ROLE_PROMPTS: Record<ChatRole, string> = {
  worker: `# 回答の立場: 労働者の味方
質問者は「働く人」です。労働者の権利を守る視点に立ち、不利益を受けていないか、どんな権利があるかを分かりやすく伝えてください。困っている場合は相談先（労働基準監督署、総合労働相談コーナー等）も案内してください。`,
  employer: `# 回答の立場: 雇用者（使用者）の実務支援
質問者は「雇う側（経営者・人事担当）」です。法令遵守の観点から、何をすべきか・どんなリスクがあるかを実務的に伝えてください。違反した場合のリスク（罰則・行政指導・トラブル）にも触れてください。`,
};

/**
 * 役割（労働者 / 雇用者）と任意の回答言語からシステムプロンプトを組み立てる。
 * lang を渡すと、その言語で回答するよう指示する（補助的な多言語対応）。
 */
export function buildSystemPrompt(role: ChatRole, lang?: string): string {
  const langInstruction = lang
    ? `\n\n# 回答言語\n回答は ${getLangLabel(lang)} で書いてください。条文番号は日本語の表記（例: 労働基準法第37条）のまま残してください。`
    : "";

  return `${COMMON_RULES}

${ROLE_PROMPTS[role]}${langInstruction}

---
# 労働基準法 主要条文の要点
${LABOR_LAW_KNOWLEDGE}`;
}
